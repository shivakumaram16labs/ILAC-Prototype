"""Convert ILAC_Demo_Datasets_v1.0/csv/*.csv into data/synthetic-data.js (browser bundle).

Rows are stored as {cols, rows} to keep the bundle small and expanded at load time.
Dataset values are kept verbatim as strings; the app parses offsets/dates where needed.
"""
import csv, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "ILAC_Demo_Datasets_v1.0" / "csv"
OUT = ROOT / "data" / "synthetic-data.js"

sheets = {}
for path in sorted(SRC.glob("*.csv")):
    with path.open(encoding="utf-8-sig", newline="") as fh:
        reader = csv.reader(fh)
        cols = next(reader)
        rows = [r for r in reader if any(c.strip() for c in r)]
    sheets[path.stem] = {"cols": cols, "rows": rows}

counts = {k: len(v["rows"]) for k, v in sheets.items()}
payload = {"version": "ILAC_Demo_Datasets_v1.0", "counts": counts, "sheets": sheets}
OUT.write_text(
    "/* Generated by scripts/build-synthetic-data.py from ILAC_Demo_Datasets_v1.0/csv. Do not edit. */\n"
    "window.ILAC_SYN = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(sum(counts.values()), "records,", len(counts), "sheets ->", OUT.relative_to(ROOT), OUT.stat().st_size, "bytes")
